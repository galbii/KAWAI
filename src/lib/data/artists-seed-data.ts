export type SocialLinkEntry = {
  platform: 'website' | 'instagram' | 'youtube' | 'spotify' | 'facebook' | 'tiktok' | 'twitter' | 'apple-music' | 'soundcloud' | 'linkedin' | 'bandcamp' | 'other'
  url: string
  label?: string
}

export type ArtistSeedEntry = {
  name: string
  slug: string
  genre?: string
  isActive: boolean
  isShigeruArtist: boolean
  region?: string
  bio: string
  shortBio?: string
  audienceMetrics?: {
    instagramFollowers?: string
    youtubeSubscribers?: string
    spotifyMonthlyListeners?: string
  }
  socialLinks: SocialLinkEntry[]
  internalNotes?: string
}

function toSlug(name: string): string {
  return name
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function buildSocialLinks(
  instagram?: string,
  facebook?: string,
  youtube?: string,
  spotify?: string,
  tiktok?: string,
  website?: string,
): SocialLinkEntry[] {
  const links: SocialLinkEntry[] = []
  if (website) links.push({ platform: 'website', url: website })
  if (instagram) links.push({ platform: 'instagram', url: instagram })
  if (youtube) links.push({ platform: 'youtube', url: youtube })
  if (spotify) links.push({ platform: 'spotify', url: spotify })
  if (facebook) links.push({ platform: 'facebook', url: facebook })
  if (tiktok) links.push({ platform: 'tiktok', url: tiktok })
  return links
}

function shortBioFrom(bio: string): string {
  if (bio.length <= 280) return bio
  const truncated = bio.slice(0, 277)
  const lastSpace = truncated.lastIndexOf(' ')
  return (lastSpace > 200 ? truncated.slice(0, lastSpace) : truncated) + '…'
}

